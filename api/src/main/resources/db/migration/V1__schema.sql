CREATE TABLE tenants (
    id VARCHAR(40) PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    token VARCHAR(80) NOT NULL UNIQUE,
    timezone VARCHAR(60) NOT NULL,
    monthly_quota INTEGER NOT NULL
);

CREATE TABLE suppressions (
    tenant_id VARCHAR(40) NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    recipient_ref VARCHAR(120) NOT NULL,
    channel VARCHAR(10) NOT NULL CHECK (channel IN ('EMAIL', 'SMS', 'PUSH')),
    reason VARCHAR(120) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (tenant_id, recipient_ref, channel)
);

CREATE TABLE campaigns (
    id VARCHAR(36) PRIMARY KEY,
    tenant_id VARCHAR(40) NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    name VARCHAR(160) NOT NULL,
    channel VARCHAR(10) NOT NULL CHECK (channel IN ('EMAIL', 'SMS', 'PUSH')),
    template VARCHAR(2000) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('SCHEDULED', 'RUNNING', 'COMPLETED', 'FAILED')),
    scheduled_at TIMESTAMP NOT NULL,
    transactional BOOLEAN NOT NULL DEFAULT FALSE,
    idempotency_key VARCHAR(120),
    created_at TIMESTAMP NOT NULL,
    started_at TIMESTAMP,
    completed_at TIMESTAMP,
    CONSTRAINT uq_campaign_idempotency UNIQUE (tenant_id, idempotency_key)
);

CREATE INDEX idx_campaigns_tenant_created ON campaigns (tenant_id, created_at DESC);
CREATE INDEX idx_campaigns_tenant_status ON campaigns (tenant_id, status);

CREATE TABLE recipients (
    tenant_id VARCHAR(40) NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    campaign_id VARCHAR(36) NOT NULL REFERENCES campaigns(id) ON DELETE CASCADE,
    recipient_ref VARCHAR(120) NOT NULL,
    email VARCHAR(254),
    phone VARCHAR(32),
    timezone VARCHAR(60),
    created_at TIMESTAMP NOT NULL,
    PRIMARY KEY (campaign_id, recipient_ref)
);

CREATE INDEX idx_recipients_campaign ON recipients (campaign_id);

CREATE TABLE notification_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id VARCHAR(40) NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    campaign_id VARCHAR(36) NOT NULL REFERENCES campaigns(id) ON DELETE CASCADE,
    recipient_ref VARCHAR(120) NOT NULL,
    channel VARCHAR(10) NOT NULL CHECK (channel IN ('EMAIL', 'SMS', 'PUSH')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'PROCESSING', 'SENT', 'FAILED', 'SKIPPED')),
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP NOT NULL,
    dedupe_key VARCHAR(64),
    last_error VARCHAR(300),
    created_at TIMESTAMP NOT NULL,
    sent_at TIMESTAMP,
    CONSTRAINT uq_job_campaign_recipient UNIQUE (campaign_id, recipient_ref),
    CONSTRAINT fk_job_recipient FOREIGN KEY (campaign_id, recipient_ref)
        REFERENCES recipients(campaign_id, recipient_ref) ON DELETE CASCADE
);

CREATE INDEX idx_jobs_tenant_due ON notification_jobs (tenant_id, status, next_attempt_at);
CREATE INDEX idx_jobs_campaign_status ON notification_jobs (campaign_id, status);

CREATE TABLE delivery_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL REFERENCES notification_jobs(id) ON DELETE CASCADE,
    attempt_no INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('SENT', 'FAILED')),
    error VARCHAR(300),
    latency_ms INTEGER,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_attempt_job_no UNIQUE (job_id, attempt_no)
);

CREATE INDEX idx_attempts_job ON delivery_attempts (job_id);
